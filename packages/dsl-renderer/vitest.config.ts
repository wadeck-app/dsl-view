import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vitest/config';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

export default defineConfig({
	plugins: [
		{
			name: 'resolve-js-to-tsx',
			enforce: 'pre',
			resolveId(id, importer) {
				if (!importer || !id.endsWith('.js')) return;
				const abs = path.resolve(path.dirname(importer), id);
				const tsx = abs.replace(/\.js$/, '.tsx');
				const ts = abs.replace(/\.js$/, '.ts');
				if (fs.existsSync(tsx)) return tsx;
				if (fs.existsSync(ts)) return ts;
			},
		},
	],
	resolve: {
		alias: [
			{ find: '@dsl-renderer', replacement: path.resolve(__dirname, './src') },
		],
	},
	test: {
		include: ['src/**/*.test.tsx', 'src/**/*.test.ts'],
		environment: 'jsdom',
		globals: true,
		setupFiles: ['./src/test-setup.ts'],
		// The generator tests parse real component sources with ts-morph (1 to 3 s each on a quiet machine). On a busy
		// one (several agents and CI jobs at once) the default 5 s made a different one of them time out on each run.
		testTimeout: 20_000,
		// A spy, stubbed env var or global left over by a failing test would otherwise leak into the next
		// test and make it fail for an unrelated reason, hiding the first real failure.
		restoreMocks: true,
		unstubEnvs: true,
		unstubGlobals: true,
		coverage: {
			provider: 'v8',
			reporter: ['text-summary', 'json-summary', 'lcov'],
			reportsDirectory: './coverage',
			include: ['src/**/*.ts', 'src/**/*.tsx'],
			// Only code that is not logic: tests and their setup, type declarations, and files that are
			// regenerated by the build (their drift tests, not line coverage, guard them).
			exclude: ['src/**/*.test.ts', 'src/**/*.test.tsx', 'src/test-setup.ts', 'src/**/*.d.ts', 'src/generated/**'],
		},
	},
});
