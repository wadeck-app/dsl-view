function route(contractKey: string, method: ResolvedRoute['method'], response: string, body?: string): ResolvedRoute {
	return { contractKey, method, responseTypeExpr: response, bodyTypeExpr: body, queryTypeExpr: undefined };
}

// Resolves "METHOD /normalized/path" from a table, and records what it was asked.
function fakeAdapter(table: Record<string, ResolvedRoute>): ContractAdapter & { asked: string[] } {
	const asked: string[] = [];
	return {
		asked,
		resolve: (method, normalizedPath) => {
			asked.push(`${method} ${normalizedPath}`);
			return table[`${method} ${normalizedPath}`] ?? null;
		},
		getImports: () => ["import { R } from 'pkg';"],
	};
}

const BOOKS_TABLE = {
	'GET /api/books/': route('/api/books/', 'GET', 'RouteResponse<A>'),
	'GET /api/books/:__p0': route('/api/books/:id', 'GET', 'RouteResponse<B>'),
	'POST /api/books/': route('/api/books/', 'POST', 'RouteResponse<C>', 'RouteBody<C>'),
};

describe('buildPageTypesFile with a contract adapter', () => {
	it('writes the typed sources, the brain bodies and the aggregated map, exactly', async () => {
		writePage(
			'books.yaml',
			[
				'$sources:',
				'  list: GET /api/books/',
				'  detail:',
				'    url: GET /api/books/{id}',
				'  nope: GET /api/zzz/',
				'$brains:',
				'  create:',
				'    $brain: $brains.$http.post',
				'    url: POST /api/books/',
				'  local:',
				'    $brain: $brains.$ctx.something',
				'    url: POST /api/books/',
				'  plain: some-string',
				'  nourl:',
				'    $brain: $brains.$http.get',
				'',
			].join('\n')
		);
		const adapter = fakeAdapter(BOOKS_TABLE);
		vi.spyOn(console, 'error').mockImplementation(() => {});

		await buildPageTypesFile(appRoot, adapter);

		expect(generated()).toBe(
			[
				'// AUTO-GENERATED by pageTypesGenerator — DO NOT EDIT',
				'// Source: src/dsl/pages/*.yaml + dsl.config.yaml',
				'',
				"import { R } from 'pkg';",
				'',
				'// ─── Page: books.yaml ───',
				'',
				'type _ContractCheck_Books_source_list = RouteResponse<A>;',
				'type _ContractCheck_Books_source_detail = RouteResponse<B>;',
				'// ERROR: No contract match for: GET /api/zzz/ (in books.yaml)',
				'// @ts-expect-error Contract not found — No contract match for: GET /api/zzz/ (in books.yaml)',
				'type _ContractCheck_Books_source_nope = never;',
				'',
				'export type BooksPageSources = {',
				'\tlist: RouteResponse<A>;',
				'\tdetail: RouteResponse<B>;',
				'\tnope: unknown;',
				'};',
				'',
				'type _ContractCheck_Books_brain_create = RouteBody<C>;',
				'',
				'export type BooksBrainBodies = {',
				'\tcreate: RouteBody<C>;',
				'};',
				'',
				'// Aggregated map of all page source types, indexed by page filename slug',
				'export type PageSourcesMap = {',
				"\t'books': BooksPageSources;",
				'};',
				'',
			].join('\n')
		);
	});

	it('asks the adapter with the method and the structurally normalized path', async () => {
		writePage('p.yaml', '$sources:\n  one: GET /api/books/{bookId}\n  two: GET /api/a/:x/b/{y}\n  three: GET /api/books/?q=1\n');
		const adapter = fakeAdapter({});
		vi.spyOn(console, 'error').mockImplementation(() => {});
		await buildPageTypesFile(appRoot, adapter);
		expect(adapter.asked).toEqual(['GET /api/books/:__p0', 'GET /api/a/:__p0/b/:__p1', 'GET /api/books/']);
	});

	it('reports every contract error once on the console, with page, kind and name', async () => {
		writePage('a.yaml', '$sources:\n  s: GET /api/zzz/\n$brains:\n  b:\n    $brain: $brains.$http.post\n    url: POST /api/zzz/\n');
		const error = vi.spyOn(console, 'error').mockImplementation(() => {});
		await buildPageTypesFile(appRoot, fakeAdapter({}));
		expect(error).toHaveBeenCalledTimes(1);
		expect(error).toHaveBeenCalledWith(
			'[pageTypesGenerator] Contract errors found:\n' +
				'  a.yaml $sources.s: No contract match for: GET /api/zzz/ (in a.yaml)\n' +
				'  a.yaml $brains.b: No contract match for: POST /api/zzz/ (in a.yaml)'
		);
		expect(generated()).toContain('type _ContractCheck_A_brain_b = never;');
		expect(generated()).toContain('// @ts-expect-error Contract not found — No contract match for: POST /api/zzz/ (in a.yaml)');
	});

	it('does not log when every URL resolves', async () => {
		writePage('a.yaml', '$sources:\n  list: GET /api/books/\n');
		const error = vi.spyOn(console, 'error').mockImplementation(() => {});
		await buildPageTypesFile(appRoot, fakeAdapter(BOOKS_TABLE));
		expect(error).not.toHaveBeenCalled();
	});

	it('flags a URL without an HTTP method prefix, for sources and brains', async () => {
		writePage('a.yaml', '$sources:\n  s: /api/books/\n$brains:\n  b:\n    $brain: $brains.$http.get\n    url: /api/books/\n');
		vi.spyOn(console, 'error').mockImplementation(() => {});
		await buildPageTypesFile(appRoot, fakeAdapter(BOOKS_TABLE));
		const out = generated();
		expect(out).toContain('// ERROR: No HTTP method prefix in URL: "/api/books/" (in a.yaml)');
		expect(out).toContain('type _ContractCheck_A_source_s = never;');
		expect(out).toContain('type _ContractCheck_A_brain_b = never;');
	});

	it('emits a brain without a body type nothing in the bodies block', async () => {
		writePage('a.yaml', '$brains:\n  b:\n    $brain: $brains.$http.get\n    url: GET /api/books/\n');
		await buildPageTypesFile(appRoot, fakeAdapter(BOOKS_TABLE));
		expect(generated()).not.toContain('BrainBodies');
		expect(generated()).not.toContain('_ContractCheck_A_brain_b');
	});

	it('gives a page with no sources an empty record type and lists several pages sorted', async () => {
		writePage('zeta-page.yaml', '$type: PageContent\n');
		writePage('alpha_page.yaml', '$sources:\n  list: GET /api/books/\n');
		writePage('notes.md', 'ignored');
		await buildPageTypesFile(appRoot, fakeAdapter(BOOKS_TABLE));
		const out = generated();
		expect(out).toContain('export type ZetaPagePageSources = Record<string, never>;');
		expect(out).toContain('export type AlphaPagePageSources = {');
		expect(out.indexOf("'alpha_page': AlphaPagePageSources;")).toBeLessThan(out.indexOf("'zeta-page': ZetaPagePageSources;"));
		expect(out).not.toContain('notes');
	});

	it('skips an empty yaml file', async () => {
		writePage('empty.yaml', '');
		writePage('real.yaml', '$type: PageContent\n');
		await buildPageTypesFile(appRoot, fakeAdapter({}));
		expect(generated()).not.toContain('empty.yaml');
		expect(generated()).toContain('real.yaml');
	});

	it('keeps a source that has no url out of the types instead of inventing one', async () => {
		writePage('a.yaml', '$sources:\n  withUrl: GET /api/books/\n  noUrl:\n    poll: 5s\n');
		await buildPageTypesFile(appRoot, fakeAdapter(BOOKS_TABLE));
		expect(generated()).toContain('\twithUrl: RouteResponse<A>;');
		expect(generated()).not.toContain('noUrl');
	});

	it('creates src/generated when it does not exist and overwrites a previous output', async () => {
		writePage('a.yaml', '$type: PageContent\n');
		await buildPageTypesFile(appRoot, fakeAdapter({}));
		fs.writeFileSync(outFile(), 'stale');
		await buildPageTypesFile(appRoot, fakeAdapter({}));
		expect(generated()).toContain('// AUTO-GENERATED by pageTypesGenerator');
	});
});

describe('buildPageTypesFile edge cases', () => {
	const occurrences = (text: string, needle: string) => text.split(needle).length - 1;

	it('ignores a source or a brain whose value is null (a key with nothing under it)', async () => {
		writePage('a.yaml', '$sources:\n  empty:\n  list: GET /api/books/\n$brains:\n  nothing:\n  ok:\n    $brain: $brains.$http.get\n    url: GET /api/books/\n');
		const error = vi.spyOn(console, 'error').mockImplementation(() => {});
		await buildPageTypesFile(appRoot, fakeAdapter(BOOKS_TABLE));
		expect(generated()).toContain('\tlist: RouteResponse<A>;');
		expect(generated()).not.toContain('empty');
		expect(generated()).not.toContain('nothing');
		expect(error).not.toHaveBeenCalled();
	});

	it('reports a URL without a method once, not a second time as an unconfigured or unmatched contract', async () => {
		writePage('a.yaml', '$sources:\n  s: /api/books/\n$brains:\n  b:\n    $brain: $brains.$http.get\n    url: /api/books/\n');
		const adapter = fakeAdapter(BOOKS_TABLE);
		vi.spyOn(console, 'error').mockImplementation(() => {});
		await buildPageTypesFile(appRoot, adapter);
		const out = generated();
		expect(occurrences(out, 'type _ContractCheck_A_source_s = never;')).toBe(1);
		expect(occurrences(out, 'type _ContractCheck_A_brain_b = never;')).toBe(1);
		expect(occurrences(out, '\ts: unknown;')).toBe(1);
		expect(adapter.asked).toEqual([]);

		await buildPageTypesFile(appRoot, null);
		expect(occurrences(generated(), 'type _ContractCheck_A_source_s = never;')).toBe(1);
	});

	it('lists in the bodies block only the brains that have a body, whatever the others are', async () => {
		writePage(
			'a.yaml',
			[
				'$brains:',
				'  noBody:',
				'    $brain: $brains.$http.get',
				'    url: GET /api/books/',
				'  withBody:',
				'    $brain: $brains.$http.post',
				'    url: POST /api/books/',
				'  broken:',
				'    $brain: $brains.$http.post',
				'    url: POST /api/zzz/',
				'',
			].join('\n')
		);
		vi.spyOn(console, 'error').mockImplementation(() => {});
		await buildPageTypesFile(appRoot, fakeAdapter(BOOKS_TABLE));
		const out = generated();
		expect(out).toContain('export type ABrainBodies = {\n\twithBody: RouteBody<C>;\n};');
		expect(occurrences(out, '\tnoBody:')).toBe(0);
		expect(occurrences(out, '\tbroken:')).toBe(0);
		expect(out).toContain('type _ContractCheck_A_brain_withBody = RouteBody<C>;');
		expect(out).toContain('type _ContractCheck_A_brain_broken = never;');
		expect(out).not.toContain('_ContractCheck_A_brain_noBody');
	});

	it('logs a single contract error (one is enough to log)', async () => {
		writePage('a.yaml', '$sources:\n  ok: GET /api/books/\n  bad: GET /api/zzz/\n');
		const error = vi.spyOn(console, 'error').mockImplementation(() => {});
		await buildPageTypesFile(appRoot, fakeAdapter(BOOKS_TABLE));
		expect(error).toHaveBeenCalledTimes(1);
		expect(error).toHaveBeenCalledWith('[pageTypesGenerator] Contract errors found:\n  a.yaml $sources.bad: No contract match for: GET /api/zzz/ (in a.yaml)');
	});

	it('does not log an error for a brain that resolves', async () => {
		writePage('a.yaml', '$brains:\n  ok:\n    $brain: $brains.$http.post\n    url: POST /api/books/\n');
		const error = vi.spyOn(console, 'error').mockImplementation(() => {});
		await buildPageTypesFile(appRoot, fakeAdapter(BOOKS_TABLE));
		expect(error).not.toHaveBeenCalled();
	});

	it('lists pages in alphabetical order whatever order the directory listing returns', async () => {
		writePage('b.yaml', '$type: PageContent\n');
		writePage('a.yaml', '$type: PageContent\n');
		vi.spyOn(fs, 'readdirSync').mockReturnValue(['b.yaml', 'a.yaml', 'x.md'] as unknown as ReturnType<typeof fs.readdirSync>);
		await buildPageTypesFile(appRoot, null);
		const out = generated();
		expect(out.indexOf("'a': APageSources;")).toBeGreaterThan(-1);
		expect(out.indexOf("'a': APageSources;")).toBeLessThan(out.indexOf("'b': BPageSources;"));
	});
});

