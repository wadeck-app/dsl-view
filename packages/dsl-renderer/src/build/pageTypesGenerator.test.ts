describe('resolveInstalledPackageEntry', () => {
	const manifest = (json: unknown) => fs.writeFileSync(path.join(appRoot, 'package.json'), JSON.stringify(json));

	it('prefers exports["."].import, then exports["."].default, then a string exports', () => {
		manifest({ exports: { '.': { import: './esm.js', default: './cjs.js' } }, main: './main.js' });
		expect(resolveInstalledPackageEntry(appRoot)).toBe(path.join(appRoot, 'esm.js'));
		manifest({ exports: { '.': { default: './cjs.js' } } });
		expect(resolveInstalledPackageEntry(appRoot)).toBe(path.join(appRoot, 'cjs.js'));
		manifest({ exports: { '.': './dot.js' } });
		expect(resolveInstalledPackageEntry(appRoot)).toBe(path.join(appRoot, 'dot.js'));
		manifest({ exports: './root.js' });
		expect(resolveInstalledPackageEntry(appRoot)).toBe(path.join(appRoot, 'root.js'));
	});

	it('falls back to module, then main, then index.js', () => {
		manifest({ module: './m.js', main: './main.js' });
		expect(resolveInstalledPackageEntry(appRoot)).toBe(path.join(appRoot, 'm.js'));
		manifest({ main: './main.js' });
		expect(resolveInstalledPackageEntry(appRoot)).toBe(path.join(appRoot, 'main.js'));
		manifest({ name: 'x' });
		expect(resolveInstalledPackageEntry(appRoot)).toBe(path.join(appRoot, 'index.js'));
	});

	it('fails with the manifest path when exports cannot be resolved to a file, or the manifest is missing', () => {
		manifest({ exports: { '.': { import: { types: './t.d.ts', default: './x.js' } } } });
		expect(() => resolveInstalledPackageEntry(appRoot)).toThrow(`${path.join(appRoot, 'package.json')}: exports["."] must resolve to a file path`);
		fs.rmSync(path.join(appRoot, 'package.json'));
		expect(() => resolveInstalledPackageEntry(appRoot)).toThrow(`no package.json in ${appRoot}`);
	});
});

// ─── Vite plugin ─────────────────────────────────────────────────────────────

type Resolved = (config: { root: string }) => Promise<void>;
const configure = (plugin: ReturnType<typeof pageTypesGenerator>, root: string) => (plugin.configResolved as unknown as Resolved)({ root });
const buildStart = (plugin: ReturnType<typeof pageTypesGenerator>) => (plugin.buildStart as unknown as () => Promise<void>)();
const hotUpdate = (plugin: ReturnType<typeof pageTypesGenerator>, file: string) => (plugin.handleHotUpdate as unknown as (c: { file: string }) => Promise<void>)({ file });

describe('pageTypesGenerator plugin', () => {
	it('is a pre-enforced plugin that uses the adapter option and prefers the appRoot option', async () => {
		writePage('a.yaml', '$sources:\n  list: GET /api/books/\n');
		const other = fs.mkdtempSync(path.join(os.tmpdir(), 'page-types-other-'));
		try {
			const plugin = pageTypesGenerator({ appRoot, adapter: fakeAdapter(BOOKS_TABLE) });
			expect(plugin.name).toBe('page-types-generator');
			expect(plugin.enforce).toBe('pre');
			await configure(plugin, other);
			await buildStart(plugin);
			expect(generated()).toContain('\tlist: RouteResponse<A>;');
			expect(fs.existsSync(path.join(other, 'src', 'generated'))).toBe(false);
		} finally {
			fs.rmSync(other, { recursive: true, force: true });
		}
	});

	it('uses the Vite root when no appRoot is given, and warns that types are unknown without contracts', async () => {
		writePage('a.yaml', '$sources:\n  list: GET /api/books/\n');
		const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
		vi.spyOn(console, 'error').mockImplementation(() => {});
		const plugin = pageTypesGenerator();
		await configure(plugin, appRoot);
		await buildStart(plugin);
		expect(warn).toHaveBeenCalledWith(
			'[pageTypesGenerator] No contracts configured in dsl.config.yaml — source/brain types will be "unknown". Add a "contracts:" section to enable typed contracts.'
		);
		expect(generated()).toContain('\tlist: unknown;');
	});

	it('regenerates on a hot update of a page yaml, however the path is spelled, and ignores everything else', async () => {
		writePage('a.yaml', '$type: PageContent\n');
		const plugin = pageTypesGenerator({ adapter: fakeAdapter({}) });
		await configure(plugin, appRoot);
		const regenerated = async (file: string) => {
			fs.rmSync(path.join(appRoot, 'src', 'generated'), { recursive: true, force: true });
			await hotUpdate(plugin, file);
			return fs.existsSync(outFile());
		};
		expect(await regenerated(path.join(pagesDir(), 'a.yaml'))).toBe(true);
		expect(await regenerated(path.join(pagesDir(), 'a.yaml').replace(/\\/g, '/'))).toBe(true);
		expect(await regenerated(path.join(pagesDir(), 'a.md'))).toBe(false);
		expect(await regenerated(path.join(appRoot, 'src', 'dsl', 'pages-old', 'a.yaml'))).toBe(false);
		expect(await regenerated(path.join(appRoot, 'src', 'x', 'a.yaml'))).toBe(false);
	});
});

describe('pageTypesGenerator contract loading from dsl.config.yaml', () => {
	const config = (text: string) => fs.writeFileSync(path.join(appRoot, 'dsl.config.yaml'), text);
	const installContracts = (name: string, source: string, manifest: Record<string, unknown> = { type: 'module', main: './index.js' }) => {
		const dir = path.join(appRoot, 'node_modules', name);
		fs.mkdirSync(dir, { recursive: true });
		fs.writeFileSync(path.join(dir, 'package.json'), JSON.stringify({ name, ...manifest }));
		fs.writeFileSync(path.join(dir, 'index.js'), source);
	};
	const ROUTES = 'export const ROUTES = { "/api/books/": { GET: { response: {} }, POST: { body: {}, response: {} } } };';

	it('imports a contracts package installed under the app, builds a Zod adapter from it and types the sources', async () => {
		installContracts('fake-contracts', ROUTES);
		config('contracts:\n  - package: fake-contracts\n    export: ROUTES\n');
		writePage('a.yaml', '$sources:\n  list: GET /api/books/\n');
		const plugin = pageTypesGenerator();
		await configure(plugin, appRoot);
		await buildStart(plugin);
		const out = generated();
		expect(out).toContain("import { ROUTES } from 'fake-contracts';");
		expect(out).toContain("\tlist: RouteResponse<'GET', '/api/books/', typeof ROUTES>;");
	});

	it('merges several contract packages: imports are concatenated and the first match wins', async () => {
		installContracts('first-contracts', 'export const FIRST = { "/api/books/": { GET: { response: {} } } };');
		installContracts('second-contracts', 'export const SECOND = { "/api/books/": { GET: { response: {} } }, "/api/authors/": { GET: { response: {} } } };');
		config(
			'contracts:\n  - package: first-contracts\n    export: FIRST\n    adapter: zod\n  - package: second-contracts\n    export: SECOND\n'
		);
		writePage('a.yaml', '$sources:\n  books: GET /api/books/\n  authors: GET /api/authors/\n');
		const plugin = pageTypesGenerator();
		await configure(plugin, appRoot);
		await buildStart(plugin);
		const out = generated();
		expect(out).toContain("import { FIRST } from 'first-contracts';");
		expect(out).toContain("import { SECOND } from 'second-contracts';");
		expect(out).toContain("\tbooks: RouteResponse<'GET', '/api/books/', typeof FIRST>;");
		expect(out).toContain("\tauthors: RouteResponse<'GET', '/api/authors/', typeof SECOND>;");
	});

	it('warns and skips an adapter kind that is not implemented, then reports that no contract is configured', async () => {
		config('contracts:\n  - package: whatever\n    export: X\n    adapter: openapi\n');
		const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
		await configure(pageTypesGenerator(), appRoot);
		expect(warn).toHaveBeenCalledWith('[pageTypesGenerator] Adapter "openapi" not yet implemented, skipping whatever');
		expect(warn).toHaveBeenCalledWith(
			'[pageTypesGenerator] No contracts configured in dsl.config.yaml — source/brain types will be "unknown". Add a "contracts:" section to enable typed contracts.'
		);
	});

	it('imports a package that is not installed under the app through the regular module resolution', async () => {
		// node:path is importable from anywhere and exports plain objects: enough to prove the bare-specifier branch.
		config('contracts:\n  - package: "node:path"\n    export: posix\n');
		const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
		await configure(pageTypesGenerator(), appRoot);
		expect(warn).not.toHaveBeenCalled();
	});

	it('merges adapters, returning null (not undefined) when none of them matches, and one set of imports per package', async () => {
		installContracts('first-contracts', 'export const FIRST = { "/api/books/": { GET: { response: {} } } };');
		const single = (await loadAdapterFromConfig({ contracts: [{ package: 'first-contracts', export: 'FIRST' }] }, appRoot))!;
		expect(single.resolve('GET', '/api/books/')).toMatchObject({ contractKey: '/api/books/', method: 'GET' });
		expect(single.resolve('GET', '/api/none/')).toBeNull();
		expect(single.getImports()).toEqual([
			"import { FIRST } from 'first-contracts';",
			"import type { RouteResponse, RouteBody, RouteQuery } from 'first-contracts';",
		]);
	});

	it('returns null (not undefined) when every declared adapter kind is skipped as not implemented', async () => {
		vi.spyOn(console, 'warn').mockImplementation(() => {});
		const contracts = [{ package: 'whatever', export: 'ROUTES', adapter: 'openapi' }] as unknown as Parameters<typeof loadAdapterFromConfig>[0]['contracts'];
		expect(await loadAdapterFromConfig({ contracts }, appRoot)).toBeNull();
	});

	it('loads no adapter without contracts, or with an empty list', async () => {
		expect(await loadAdapterFromConfig({}, appRoot)).toBeNull();
		expect(await loadAdapterFromConfig({ contracts: [] }, appRoot)).toBeNull();
	});

	it('does not warn about missing contracts when the section is empty-but-declared and an adapter loaded', async () => {
		installContracts('fake-contracts', ROUTES);
		config('contracts:\n  - package: fake-contracts\n    export: ROUTES\n');
		const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
		await configure(pageTypesGenerator(), appRoot);
		expect(warn).not.toHaveBeenCalled();
	});

	it('fails the build, naming the package and the dependency to add, when the package cannot be imported', async () => {
		config('contracts:\n  - package: not-installed-anywhere-xyz\n    export: ROUTES\n');
		await expect(configure(pageTypesGenerator(), appRoot)).rejects.toThrow(
			/\[pageTypesGenerator\] Cannot import contract package "not-installed-anywhere-xyz"\. Make sure it is listed in package\.json dependencies\./
		);
	});

	it('fails the build, naming the export, when the package does not export an ApiRoutes object', async () => {
		installContracts('fake-contracts', 'export const NOT_ROUTES = 5; export const ROUTES = null;');
		for (const exportName of ['MISSING', 'NOT_ROUTES', 'ROUTES']) {
			config(`contracts:\n  - package: fake-contracts\n    export: ${exportName}\n`);
			await expect(configure(pageTypesGenerator(), appRoot)).rejects.toThrow(
				`[pageTypesGenerator] Export "${exportName}" from "fake-contracts" is not a valid ApiRoutes object.`
			);
		}
	});

	it("real Node's ESM loader imports the resolved entry as a file URL but rejects the bare package directory (why the entry is resolved)", () => {
		installContracts('fake-contracts', ROUTES);
		const packageDir = path.join(appRoot, 'node_modules', 'fake-contracts');
		const script = (specifier: string) => `import(${JSON.stringify(specifier)}).then(() => process.exit(0), (e) => { console.error(e.code); process.exit(1); })`;
		const run = (specifier: string) => spawnSync(process.execPath, ['--input-type=module', '-e', script(specifier)], { encoding: 'utf-8' });

		expect(run(pathToFileURL(resolveInstalledPackageEntry(packageDir)).href).status).toBe(0);
		const bare = run(packageDir);
		expect(bare.status).toBe(1);
		expect(bare.stderr).toMatch(/ERR_UNSUPPORTED_(ESM_URL_SCHEME|DIR_IMPORT)/);
	});

	it('fails the build with the package path when the installed package manifest is unusable', async () => {
		const dir = path.join(appRoot, 'node_modules', 'broken-contracts');
		fs.mkdirSync(dir, { recursive: true });
		config('contracts:\n  - package: broken-contracts\n    export: ROUTES\n');
		await expect(configure(pageTypesGenerator(), appRoot)).rejects.toThrow(/Cannot import contract package "broken-contracts".*no package\.json in /s);
	});
});
