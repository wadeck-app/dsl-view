import fs from 'fs';
import { load as parseYaml } from 'js-yaml';
import path from 'path';
import type { Plugin } from 'vite';

export interface PageRoute {
	/** Source YAML filename, e.g. `worker-detail.yaml`. */
	filename: string;
	route: string;
	navLabel?: string;
	navOrder?: number;
}

export interface RawPage {
	filename: string;
	doc: Record<string, unknown>;
}

// Two patterns match the same URLs when only their param names differ (/w/:id vs /w/:workerId).
export function normalizeRouteForComparison(route: string): string {
	const withoutTrailingSlash = route.length > 1 ? route.replace(/\/+$/, '') : route;
	return withoutTrailingSlash.replace(/:[A-Za-z0-9_]+/g, ':');
}

export function collectPageRoutes(pages: RawPage[]): PageRoute[] {
	const routes: PageRoute[] = [];
	const seen = new Map<string, PageRoute>();

	for (const { filename, doc } of pages) {
		const route = doc['$route'];
		if (route === undefined) continue;
		if (typeof route !== 'string' || !route.startsWith('/')) {
			throw new Error(`[routesGenerator] ${filename}: $route must be a string starting with '/', got ${JSON.stringify(route)}`);
		}

		const key = normalizeRouteForComparison(route);
		const previous = seen.get(key);
		if (previous) {
			const detail =
				previous.route === route
					? ''
					: ` ('${previous.route}' in ${previous.filename} matches the same URLs - they differ only by param name)`;
			throw new Error(`[routesGenerator] Duplicate $route '${route}' in ${previous.filename} and ${filename}${detail}`);
		}

		const entry: PageRoute = { filename, route };
		if (typeof doc['$navLabel'] === 'string') entry.navLabel = doc['$navLabel'];
		if (typeof doc['$navOrder'] === 'number') entry.navOrder = doc['$navOrder'];
		seen.set(key, entry);
		routes.push(entry);
	}

	return routes;
}

function toIdentifier(filename: string): string {
	const base = filename.replace(/\.yaml$/, '');
	const camel = base.replace(/[^A-Za-z0-9]+(.)?/g, (_m, c: string | undefined) => (c ? c.toUpperCase() : ''));
	return `${/^[0-9]/.test(camel) ? '_' : ''}${camel}Yaml`;
}

function generateRoutesFile(routes: PageRoute[]): string {
	const lines: string[] = [
		'// GENERATED by routesGenerator - do not edit. Source: src/dsl/pages/*.yaml ($route, $navLabel, $navOrder)',
		'',
	];
	for (const r of routes) {
		lines.push(`import ${toIdentifier(r.filename)} from '../dsl/pages/${r.filename}?raw';`);
	}
	lines.push('', 'export const dslRoutes = [');
	for (const r of routes) {
		const fields = [`route: '${r.route}'`, `yamlText: ${toIdentifier(r.filename)}`, `source: '${r.filename}'`];
		if (r.navLabel !== undefined) fields.push(`navLabel: ${JSON.stringify(r.navLabel)}`);
		if (r.navOrder !== undefined) fields.push(`navOrder: ${r.navOrder}`);
		lines.push(`\t{ ${fields.join(', ')} },`);
	}
	lines.push('] as const;', '');
	return lines.join('\n');
}

export function buildRoutesFile(appRoot: string): void {
	const pagesDir = path.join(appRoot, 'src', 'dsl', 'pages');
	if (!fs.existsSync(pagesDir)) {
		console.warn('[routesGenerator] No src/dsl/pages directory found, skipping.');
		return;
	}

	const pages: RawPage[] = fs
		.readdirSync(pagesDir)
		.filter((f) => f.endsWith('.yaml'))
		.sort()
		.map((filename) => ({
			filename,
			doc: (parseYaml(fs.readFileSync(path.join(pagesDir, filename), 'utf-8')) ?? {}) as Record<string, unknown>,
		}));

	// Throws on a duplicate route before anything is written.
	const routes = collectPageRoutes(pages);

	const generatedDir = path.join(appRoot, 'src', 'generated');
	fs.mkdirSync(generatedDir, { recursive: true });
	fs.writeFileSync(path.join(generatedDir, 'routes.ts'), generateRoutesFile(routes), 'utf-8');
}

export interface RoutesGeneratorOptions {
	appRoot?: string;
}

export function routesGenerator(options: RoutesGeneratorOptions = {}): Plugin {
	let appRoot = '';

	return {
		name: 'routes-generator',
		enforce: 'pre',

		configResolved(config) {
			appRoot = options.appRoot ?? config.root;
		},

		buildStart() {
			buildRoutesFile(appRoot);
		},

		handleHotUpdate({ file }) {
			const pagesDir = path.join(appRoot, 'src', 'dsl', 'pages');
			if (file.endsWith('.yaml') && file.startsWith(pagesDir)) {
				buildRoutesFile(appRoot);
			}
		},
	};
}
