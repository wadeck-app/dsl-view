import fs from 'fs';
import os from 'os';
import path from 'path';
import ts from 'typescript';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { buildRoutesFile, collectPageRoutes, normalizeRouteForComparison, routesGenerator } from './routesGenerator.js';

describe('normalizeRouteForComparison edge cases', () => {
	it('keeps the root route as "/" and strips every trailing slash of longer routes', () => {
		expect(normalizeRouteForComparison('/')).toBe('/');
		expect(normalizeRouteForComparison('//')).toBe('/');
		expect(normalizeRouteForComparison('/a///')).toBe('/a');
	});

	it('replaces params with letters, digits and underscores, and only after a colon', () => {
		expect(normalizeRouteForComparison('/a/:id_2/b/:Name9')).toBe('/a/:/b/:');
		expect(normalizeRouteForComparison('/a:b')).toBe('/a:');
	});
});

describe('collectPageRoutes validation', () => {
	it.each([
		['a number', 5],
		['a path without a leading slash', 'workers'],
		['an empty string', ''],
		['null (a `$route:` with no value)', null],
	])('rejects a $route that is %s, naming the file and the value', (_name, route) => {
		expect(() => collectPageRoutes([{ filename: 'a.yaml', doc: { $route: route } }])).toThrow(
			`[routesGenerator] a.yaml: $route must be a string starting with '/', got ${JSON.stringify(route)}`
		);
	});

	it('accepts the root route', () => {
		expect(collectPageRoutes([{ filename: 'home.yaml', doc: { $route: '/' } }])).toEqual([{ filename: 'home.yaml', route: '/', navVisible: true }]);
	});

	it('words an exact duplicate differently from a param-name-only duplicate', () => {
		const exact = () =>
			collectPageRoutes([
				{ filename: 'a.yaml', doc: { $route: '/x' } },
				{ filename: 'b.yaml', doc: { $route: '/x' } },
			]);
		expect(exact).toThrow(/^\[routesGenerator\] Duplicate \$route '\/x' in a\.yaml and b\.yaml$/);
		const byName = () =>
			collectPageRoutes([
				{ filename: 'a.yaml', doc: { $route: '/x/:id' } },
				{ filename: 'b.yaml', doc: { $route: '/x/:key' } },
			]);
		expect(byName).toThrow("Duplicate $route '/x/:key' in a.yaml and b.yaml ('/x/:id' in a.yaml matches the same URLs - they differ only by param name)");
	});

	it('does not treat $navVisible: true as an extra, and accepts it', () => {
		const [r] = collectPageRoutes([{ filename: 'a.yaml', doc: { $route: '/a', $navVisible: true } }]);
		expect(r).toEqual({ filename: 'a.yaml', route: '/a', navVisible: true });
	});

	it('lets $navLabel: false win over $navVisible: true', () => {
		const [r] = collectPageRoutes([{ filename: 'a.yaml', doc: { $route: '/a', $navLabel: false, $navVisible: true } }]);
		expect(r!.navVisible).toBe(false);
	});

	it('maps $navX to a one-letter extra, and ignores a bare $nav key', () => {
		const [withX] = collectPageRoutes([{ filename: 'a.yaml', doc: { $route: '/a', $navX: 1 } }]);
		expect(withX!.navExtra).toEqual({ x: 1 });
		const [bare] = collectPageRoutes([{ filename: 'a.yaml', doc: { $route: '/a', $nav: 1 } }]);
		expect(bare).not.toHaveProperty('navExtra');
	});

	it('keeps $navOrder: 0', () => {
		const [r] = collectPageRoutes([{ filename: 'a.yaml', doc: { $route: '/a', $navOrder: 0 } }]);
		expect(r!.navOrder).toBe(0);
	});
});

describe('buildRoutesFile output', () => {
	let appRoot: string;
	const pages = () => path.join(appRoot, 'src', 'dsl', 'pages');
	const routesFile = () => path.join(appRoot, 'src', 'generated', 'routes.ts');

	beforeEach(() => {
		appRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'routes-generator-output-'));
		fs.mkdirSync(pages(), { recursive: true });
	});

	afterEach(() => {
		vi.restoreAllMocks();
		fs.rmSync(appRoot, { recursive: true, force: true });
	});

	it('writes exactly this file for a page with every nav field and one without', () => {
		fs.writeFileSync(path.join(pages(), 'worker-detail.yaml'), '$route: /workers/:id\n$navLabel: Worker\n$navOrder: 0\n$navBadge: { field: n }\n$type: PageContent\n');
		fs.writeFileSync(path.join(pages(), 'hidden.yaml'), '$route: /hidden\n$navVisible: false\n$type: PageContent\n');

		buildRoutesFile(appRoot);

		expect(fs.readFileSync(routesFile(), 'utf-8')).toBe(
			[
				'// GENERATED by routesGenerator - do not edit. Source: src/dsl/pages/*.yaml ($route, $navLabel, $navOrder)',
				'',
				"import hiddenYaml from '../dsl/pages/hidden.yaml?raw';",
				"import workerDetailYaml from '../dsl/pages/worker-detail.yaml?raw';",
				'',
				'export interface DslRouteEntry {',
				'\troute: string;',
				'\tyamlText: string;',
				'\t/** Source YAML filename. */',
				'\tsource: string;',
				'\tnavLabel?: string;',
				'\tnavOrder?: number;',
				'\t/** False when the page is hidden from nav ($navVisible: false or $navLabel: false); the route still exists. */',
				'\tnavVisible: boolean;',
				'\t/** Other $nav<Name> keys as { name: value }; the consumer owns their meaning (e.g. badge). */',
				'\tnavExtra?: Record<string, unknown>;',
				'}',
				'',
				'export const dslRoutes: readonly DslRouteEntry[] = [',
				"\t{ route: '/hidden', yamlText: hiddenYaml, source: 'hidden.yaml', navVisible: false },",
				"\t{ route: '/workers/:id', yamlText: workerDetailYaml, source: 'worker-detail.yaml', navLabel: \"Worker\", navOrder: 0, navVisible: true, navExtra: {\"badge\":{\"field\":\"n\"}} },",
				'];',
				'',
			].join('\n')
		);
	});

	it('lists pages in alphabetical order whatever order the directory listing returns', () => {
		fs.writeFileSync(path.join(pages(), 'b.yaml'), '$route: /b\n');
		fs.writeFileSync(path.join(pages(), 'a.yaml'), '$route: /a\n');
		vi.spyOn(fs, 'readdirSync').mockReturnValue(['b.yaml', 'a.yaml', 'readme.md'] as unknown as ReturnType<typeof fs.readdirSync>);

		buildRoutesFile(appRoot);

		const out = fs.readFileSync(routesFile(), 'utf-8');
		expect(out.indexOf("route: '/a'")).toBeGreaterThan(-1);
		expect(out.indexOf("route: '/a'")).toBeLessThan(out.indexOf("route: '/b'"));
		expect(out).not.toContain('readme');
	});

	it('warns and writes nothing when there is no pages directory', () => {
		const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
		fs.rmSync(path.join(appRoot, 'src'), { recursive: true, force: true });

		buildRoutesFile(appRoot);

		expect(warn).toHaveBeenCalledWith('[routesGenerator] No src/dsl/pages directory found, skipping.');
		expect(fs.existsSync(routesFile())).toBe(false);
	});

	it('can regenerate over an existing generated directory, and treats an empty page file as having no route', () => {
		fs.writeFileSync(path.join(pages(), 'a.yaml'), '$route: /a\n');
		fs.writeFileSync(path.join(pages(), 'empty.yaml'), '');
		buildRoutesFile(appRoot);
		buildRoutesFile(appRoot);
		const out = fs.readFileSync(routesFile(), 'utf-8');
		expect(out).toContain("route: '/a'");
		expect(out).not.toContain('empty');
	});

	it('derives a valid identifier for awkward filenames', () => {
		fs.writeFileSync(path.join(pages(), '404.yaml'), '$route: /404\n');
		fs.writeFileSync(path.join(pages(), 'ends-.yaml'), '$route: /ends\n');
		fs.writeFileSync(path.join(pages(), 'multi__sep--x.yaml'), '$route: /multi\n');
		buildRoutesFile(appRoot);
		const out = fs.readFileSync(routesFile(), 'utf-8');
		expect(out).toContain("import _404Yaml from '../dsl/pages/404.yaml?raw';");
		expect(out).toContain("import endsYaml from '../dsl/pages/ends-.yaml?raw';");
		expect(out).toContain("import multiSepXYaml from '../dsl/pages/multi__sep--x.yaml?raw';");
	});

	it('fails when two filenames map to the same identifier, naming both, and writes nothing', () => {
		fs.writeFileSync(path.join(pages(), 'a-b.yaml'), '$route: /one\n');
		fs.writeFileSync(path.join(pages(), 'a_b.yaml'), '$route: /two\n');
		expect(() => buildRoutesFile(appRoot)).toThrow(
			'[routesGenerator] a-b.yaml and a_b.yaml both map to the identifier aBYaml in the generated routes file; rename one of them'
		);
		expect(fs.existsSync(routesFile())).toBe(false);
	});

	it('escapes quotes and backslashes in a route so the generated file stays valid TypeScript', () => {
		fs.writeFileSync(path.join(pages(), 'q.yaml'), '$route: "/it\'s/a\\\\b"\n');
		buildRoutesFile(appRoot);
		const out = fs.readFileSync(routesFile(), 'utf-8');
		expect(out).toContain("route: '/it\\'s/a\\\\b'");
		const transpiled = ts.transpileModule(out, { reportDiagnostics: true, compilerOptions: { target: ts.ScriptTarget.ES2022 } });
		expect(transpiled.diagnostics).toEqual([]);
	});
});

describe('routesGenerator Vite plugin', () => {
	let appRoot: string;
	const pages = () => path.join(appRoot, 'src', 'dsl', 'pages');
	const routesFile = () => path.join(appRoot, 'src', 'generated', 'routes.ts');
	type HotUpdate = (ctx: { file: string }) => void;
	const resolved = (plugin: ReturnType<typeof routesGenerator>, root: string) => (plugin.configResolved as unknown as (c: { root: string }) => void)({ root });

	beforeEach(() => {
		appRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'routes-generator-plugin-'));
		fs.mkdirSync(pages(), { recursive: true });
		fs.writeFileSync(path.join(pages(), 'a.yaml'), '$route: /a\n');
	});

	afterEach(() => {
		fs.rmSync(appRoot, { recursive: true, force: true });
	});

	it('is a pre-enforced plugin named routes-generator that builds at buildStart from the Vite root', () => {
		const plugin = routesGenerator();
		expect(plugin.name).toBe('routes-generator');
		expect(plugin.enforce).toBe('pre');
		resolved(plugin, appRoot);
		(plugin.buildStart as unknown as () => void)();
		expect(fs.readFileSync(routesFile(), 'utf-8')).toContain("route: '/a'");
	});

	it('prefers the appRoot option over the Vite root', () => {
		const other = fs.mkdtempSync(path.join(os.tmpdir(), 'routes-generator-other-'));
		try {
			const plugin = routesGenerator({ appRoot });
			resolved(plugin, other);
			(plugin.buildStart as unknown as () => void)();
			expect(fs.existsSync(routesFile())).toBe(true);
			expect(fs.existsSync(path.join(other, 'src', 'generated', 'routes.ts'))).toBe(false);
		} finally {
			fs.rmSync(other, { recursive: true, force: true });
		}
	});

	it('regenerates on a hot update of a page yaml, however the path is spelled, and ignores everything else', () => {
		const plugin = routesGenerator();
		resolved(plugin, appRoot);
		const hot = plugin.handleHotUpdate as unknown as HotUpdate;
		const regenerated = (file: string) => {
			fs.rmSync(path.join(appRoot, 'src', 'generated'), { recursive: true, force: true });
			hot({ file });
			return fs.existsSync(routesFile());
		};
		const posixPage = path.join(pages(), 'a.yaml').replace(/\\/g, '/');
		expect(regenerated(path.join(pages(), 'a.yaml'))).toBe(true);
		// Vite reports posix separators even on Windows.
		expect(regenerated(posixPage)).toBe(true);
		expect(regenerated(path.join(pages(), 'sub', 'deep.yaml'))).toBe(true);
		expect(regenerated(path.join(pages(), 'a.md'))).toBe(false);
		expect(regenerated(path.join(appRoot, 'src', 'dsl', 'pages-old', 'a.yaml'))).toBe(false);
		expect(regenerated(path.join(appRoot, 'src', 'other', 'a.yaml'))).toBe(false);
	});
});
